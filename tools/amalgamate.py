#!/usr/bin/env python3
"""Builds the single-header distribution dist/cbat.h.

Usage: python tools/amalgamate.py [--output dist/cbat.h]

The module order is read from `set(CBAT_MODULES ...)` in CMakeLists.txt so it
never drifts from the real build. Headers are concatenated first; sources go
inside `#ifdef CBAT_IMPLEMENTATION`. Regions of a source marked with
`cbat:feature-macros-begin/end` (e.g. _POSIX_C_SOURCE) are hoisted to the very
top of the file, because feature-test macros must precede every system header.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"cbat/[a-z_]+\.h"\s*$')
FEATURE_REGION = re.compile(
    r"/\* cbat:feature-macros-begin \*/\n(.*?)/\* cbat:feature-macros-end \*/\n",
    re.S,
)


def read_modules():
    cmake = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = re.search(r"set\(CBAT_MODULES\s+(.*?)\)", cmake, re.S)
    if not match:
        sys.exit("amalgamate: could not find set(CBAT_MODULES ...) in CMakeLists.txt")
    optional = re.search(r"set\(CBAT_OPTIONAL_MODULES\s+(.*?)\)", cmake, re.S)
    return match.group(1).split(), optional.group(1).split() if optional else []


def strip_local_includes(text):
    return "\n".join(
        line for line in text.splitlines() if not LOCAL_INCLUDE.match(line)
    ) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", default=str(ROOT / "dist" / "cbat.h"))
    args = parser.parse_args()

    modules, optional = read_modules()
    modules += optional
    version = re.search(
        r'#define CBAT_VERSION_STRING "([^"]+)"',
        (ROOT / "include" / "cbat" / "base.h").read_text(encoding="utf-8"),
    ).group(1)

    feature_blocks = []
    sources = []
    for module in modules:
        text = (ROOT / "src" / f"{module}.c").read_text(encoding="utf-8")
        for block in FEATURE_REGION.findall(text):
            if block not in feature_blocks:
                feature_blocks.append(block)
        text = FEATURE_REGION.sub("", text)
        block = f"/* ==== src/{module}.c ==== */\n" + strip_local_includes(text)
        if module in optional:
            flag = "CBAT_WITH_" + module.upper()
            condition = f"(!defined({flag}) || {flag})"
            if module in ("linalg", "ml"):
                condition += " && (!defined(CBAT_WITH_NDARRAY) || CBAT_WITH_NDARRAY)"
            block = f"#if {condition}\n" + block + "#endif\n"
        sources.append(block)

    headers = []
    for module in modules:
        text = (ROOT / "include" / "cbat" / f"{module}.h").read_text(encoding="utf-8")
        block = f"/* ==== include/cbat/{module}.h ==== */\n" + strip_local_includes(text)
        if module in optional:
            flag = "CBAT_WITH_" + module.upper()
            condition = f"(!defined({flag}) || {flag})"
            if module in ("linalg", "ml"):
                condition += " && (!defined(CBAT_WITH_NDARRAY) || CBAT_WITH_NDARRAY)"
            block = f"#if {condition}\n" + block + "#endif\n"
        headers.append(block)

    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8").strip()
    out = []
    out.append("/*\n * cbat.h - C Batteries Included %s, single-header edition.\n" % version)
    out.append(" * Generated by tools/amalgamate.py - do not edit.\n *\n")
    out.append(" * In exactly ONE .c file, before including any other header:\n")
    out.append(" *     #define CBAT_IMPLEMENTATION\n *     #include \"cbat.h\"\n *\n")
    for line in license_text.splitlines():
        out.append((" * " + line).rstrip() + "\n")
    out.append(" */\n#ifndef CBAT_SINGLE_HEADER_H\n#define CBAT_SINGLE_HEADER_H\n\n")
    if feature_blocks:
        out.append("#ifdef CBAT_IMPLEMENTATION\n")
        out.extend(feature_blocks)
        out.append("#endif /* CBAT_IMPLEMENTATION */\n\n")
    out.extend(headers)
    out.append("\n#endif /* CBAT_SINGLE_HEADER_H */\n\n")
    out.append("#if defined(CBAT_IMPLEMENTATION) && !defined(CBAT_IMPLEMENTATION_DONE)\n")
    out.append("#define CBAT_IMPLEMENTATION_DONE\n")
    out.extend(sources)
    out.append("#endif /* CBAT_IMPLEMENTATION */\n")

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"amalgamate: wrote {output} ({len(modules)} modules)")


if __name__ == "__main__":
    main()
