#!/usr/bin/env python3
"""Generate docs/API.md from public headers; --check rejects stale output."""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKEN = re.compile(r'/\*[\s\S]*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\bCBAT_API\b|^typedef\b', re.M)


def clean_comment(comment):
    body = re.sub(r'^/\*\*?\s*|\*/$', '', comment).strip()
    return '\n'.join(re.sub(r'^\s*\* ?', '', line).rstrip()
                     for line in body.splitlines()).strip()


def declaration_end(text, start):
    """Find a top-level semicolon, skipping comments, strings and struct fields."""
    depth = 0
    token = re.compile(r'/\*[\s\S]*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{};]')
    for match in token.finditer(text, start):
        value = match.group()
        if value == '{':
            depth += 1
        elif value == '}':
            depth -= 1
        elif value == ';' and depth == 0:
            return match.end()
    raise ValueError('unterminated public declaration')


def declarations(text):
    """Yield (signature, adjacent documentation) without executing header text."""
    consumed = 0
    comment = None
    comment_end = 0
    for match in TOKEN.finditer(text):
        if match.start() < consumed:
            continue
        token = match.group()
        if token.startswith('/*'):
            comment = clean_comment(token) if token.startswith('/**') else None
            comment_end = match.end()
        elif token in ('CBAT_API', 'typedef'):
            end = declaration_end(text, match.start())
            doc = comment if not text[comment_end:match.start()].strip() else None
            signature = text[match.start():end].strip()
            # Preserve multiline structs and typedefs; normalize function indentation.
            if token == 'CBAT_API':
                signature = re.sub(r'\s+', ' ', signature)
            yield signature, doc
            consumed = end
            comment = None


def render(headers):
    output = ['# cbat API reference', '',
              'Generated by `python tools/gen_api_docs.py`; edit the public headers,',
              'then regenerate this file. Declarations and adjacent documentation are',
              'copied from the headers. Undocumented declarations link back to the source.',
              '', 'For conventions and ownership rules, see [DESIGN.md](DESIGN.md).', '',
              '## Modules', '']
    for path in headers:
        output.append(f'- [{path.stem}](#{path.stem})')
    for path in headers:
        text = path.read_text(encoding='utf-8')
        output += ['', f'## {path.stem}', '',
                   f'Source: [`cbat/{path.name}`](../include/cbat/{path.name})', '']
        opening = re.match(r'\s*(/\*[\s\S]*?\*/)', text)
        if opening:
            # Fenced text preserves sample C and literal Markdown characters.
            output += ['```text', clean_comment(opening.group(1)), '```', '']
        for signature, doc in declarations(text):
            output += ['```c', signature, '```', '']
            if doc:
                output += [doc, '']
    return '\n'.join(output).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=pathlib.Path, default=ROOT / 'docs/API.md')
    args = parser.parse_args()
    result = render(sorted((ROOT / 'include/cbat').glob('*.h')))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding='utf-8') != result:
            print('API reference is stale. Run python tools/gen_api_docs.py.', file=sys.stderr)
            return 1
        print('API reference is up to date.')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding='utf-8', newline='\n')
        print(f'Generated {args.output}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
