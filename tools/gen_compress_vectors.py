#!/usr/bin/env python3
"""Rebuild compression fixtures/corpus with Python's independent zlib/zipfile."""
import gzip
import io
import pathlib
import struct
import zipfile
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def archive(stream=False, force=False):
    class Pipe(io.BytesIO):
        def seek(self, *args):
            raise io.UnsupportedOperation()

    output = Pipe() if stream else io.BytesIO()
    with zipfile.ZipFile(output, "w") as handle:
        for name, data, method in [
            ("plain.bin", b"plain\0bytes", 0),
            ("hello.txt", b"hello " * 1000, 8),
            ("folder/", b"", 0),
        ]:
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = method
            if force:
                with handle.open(info, "w", force_zip64=True) as entry:
                    entry.write(data)
            else:
                handle.writestr(info, data)
    return output.getvalue()


def main():
    payload = bytes((i * 17) % 256 if i % 97 == 0 else ord("a") + i % 7 for i in range(8192))
    raw = zlib.compress(payload, wbits=-15)
    assert (raw[0] >> 1) & 3 == 2
    normal = archive()
    end_at = len(normal) - 22
    count, size, offset = struct.unpack_from("<HII", normal, end_at + 10)
    record = struct.pack("<IQHHIIQQQQ", 0x06064B50, 44, 45, 45, 0, 0, count, count, size, offset)
    locator = struct.pack("<IIQI", 0x07064B50, 0, end_at, 1)
    end = bytearray(normal[end_at:])
    struct.pack_into("<HHII", end, 8, 65535, 65535, 0xFFFFFFFF, 0xFFFFFFFF)
    zip64 = normal[:end_at] + record + locator + end
    assert zipfile.ZipFile(io.BytesIO(zip64)).read("hello.txt") == b"hello " * 1000
    vectors = {
        "dynamic_deflate": raw,
        "normal_zip": normal,
        "stream_zip": archive(True, True),
        "zip64_archive": zip64,
    }
    lines = ["/* Generated by tools/gen_compress_vectors.py with Python zlib/zipfile. */"]
    for name, value in vectors.items():
        lines.append("static const unsigned char " + name + "[] = {")
        for at in range(0, len(value), 16):
            lines.append("    " + ",".join(f"0x{x:02x}" for x in value[at:at + 16]) + ",")
        lines.append("};")
    (ROOT / "tests/compress_vectors.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    corpus = ROOT / "fuzz/corpus/compress"
    corpus.mkdir(parents=True, exist_ok=True)
    for name, value in vectors.items():
        (corpus / name).write_bytes(value)
    (corpus / "gzip").write_bytes(gzip.compress(payload, mtime=0))


if __name__ == "__main__":
    main()
